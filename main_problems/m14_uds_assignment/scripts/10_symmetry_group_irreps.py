def cycle_aut(N):
    """驗證 C_N 之自同構群 = D_N（旋轉 N 個 ＋ 反射 N 個）。"""
    edges = {(i, (i + 1) % N) for i in range(N)}
    rots = [(lambda x, s=s: (x + s) % N) for s in range(N)]
    refs = [(lambda x, s=s: (s - x) % N) for s in range(N)]
    cands = rots + refs
    ok = 0
    for f in cands:
        e2 = set()
        for (i, j) in edges:
            a, b = f(i), f(j)
            e2.add((a, b) if a < b else (b, a))
        e1 = {(a, b) if a < b else (b, a) for (a, b) in edges}
        if e2 == e1:
            ok += 1
    return ok, len(cands)


def path_aut(N):
    """P_N（44-站 Dirichlet 鏈）之自同構群 = ℤ₂（n ↦ N+1−n）。"""
    edges = {(i, i + 1) for i in range(1, N)}
    ids = list(range(1, N + 1))
    ok = 0
    for perm in (ids, ids[::-1]):
        e2 = {(perm[i - 1], perm[i]) for (i, _) in edges}
        e2uj = {tuple(sorted(e)) for e in e2}
        e1uj = {tuple(sorted(e)) for e in edges}
        if e2uj == e1uj:
            ok += 1
    return ok


