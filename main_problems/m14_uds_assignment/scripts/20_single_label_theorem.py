import mpmath as mp

mp.mp.dps = 60
L = "=" * 78
ND = 44


def spec(den, M):
    return [4 * mp.sin(n * mp.pi / den) ** 2 for n in range(1, M + 1)]


def vandermonde_det(vals):
    """det(v_i^(j-1))，i,j = 1..m —— 用 mpmath 之 LU。"""
    m = len(vals)
    A = mp.matrix(m, m)
    for i in range(m):
        x = mp.mpf(1)
        for j in range(m):
            A[i, j] = x
            x *= vals[i]
    return mp.det(A)


print(L)
print("M14 scripts/20 — 單標籤定理（交換代數 = 對角代數）")
print(L)

for label, den in [("/90 Dirichlet 44 站", 90), ("/88 週期 44 模式", 88)]:
    v = spec(den, ND)
    inc = all(v[i] < v[i + 1] for i in range(ND - 1))
    print(f"\n  {label}")
    print(f"    γ 嚴格遞增（⟹ 特徵值互異）？{inc}")
    print(f"    γ_1 = {mp.nstr(v[0],8)} … γ_44 = {mp.nstr(v[-1],8)}")
    d = vandermonde_det(v)
    print(f"    Vandermonde det = {mp.nstr(d, 10)}")
    print(f"    |det| > 0 ？{abs(d) > mp.mpf('1e-40')} ⟹ {{p(H)}} 之維數 = {ND}")

print("\n" + L)
print("【定理】")
print(L)
