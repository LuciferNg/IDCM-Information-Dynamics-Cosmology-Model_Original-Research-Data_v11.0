"""
M14 scripts/30 — ℚ(√2) 扇區階梯（X1）：/88 等差（√2）vs /90 等比（φ²）

────────────────────────────────────────────────────────────────────────
殘留：docs/28 §六 X1（/88 之 ℚ(√2) 扇區有無自身階梯）
延伸：X1 之全鏈掃描 —— 兩鏈有無**任何**三模等比（乘性階梯）

判準（跑前凍結）
  T1 等差（AP）：γ_b − γ_a = γ_c − γ_b（a<b<c，互異），容差 1e−40。
  T2 等比（GP）：γ_b² = γ_a·γ_c（a<b<c，互異），容差 1e−40（相對）。
  T3 「階梯」= 三項且中間模為幾何／算術中項；只報存在性，不凑質量比。
性質：確定性窮舉 C(44,3)=13,244。N_trials = 0。dps = 60。零觀測量。
────────────────────────────────────────────────────────────────────────
"""
import itertools

import mpmath as mp

mp.mp.dps = 60
L = "=" * 78
N = 44
TOL = mp.mpf('1e-40')


def gam(x, n):
    return 4 * mp.sin(n * mp.pi / x) ** 2


print(L)
print("M14 scripts/30 — ℚ(√2) 階梯（X1）：/88 等差 vs /90 等比")
print(L)

# ============================================================================
print("\n【§一】/88 之 ℚ(√2) 扇區：/8 子鏈之三項結構")
m = [11, 22, 33, 44]
g = {n: gam(88, n) for n in m}
print(f"  γ11 = {mp.nstr(g[11], 18)}  (2−√2)")
print(f"  γ22 = {mp.nstr(g[22], 18)}  (2)")
print(f"  γ33 = {mp.nstr(g[33], 18)}  (2+√2)")
print(f"  γ44 = {mp.nstr(g[44], 18)}  (4, Nyquist)")
d1, d2 = g[22] - g[11], g[33] - g[22]
print(f"\n  AP 檢定：γ22 − γ11 = {mp.nstr(d1, 16)}；γ33 − γ22 = {mp.nstr(d2, 16)}")
print(f"            |d1 − d2| = {mp.nstr(abs(d1 - d2), 3)}；d = √2 = {mp.nstr(mp.sqrt(2), 16)}")
print(f"            |d1 − √2| = {mp.nstr(abs(d1 - mp.sqrt(2)), 3)}")
print(f"  ⟹ **等差，公差 √2**，中心 γ22 = 2 = γ_max/2（γ11 + γ33 = 4 = 2·γ22）")
gp = g[22] ** 2 - g[11] * g[33]
print(f"  GP 檢定：γ22² − γ11·γ33 = {mp.nstr(gp, 6)} ⟹ **非等比**")
print(f"  比值：γ11:γ22:γ33 = 1 : {mp.nstr(g[22]/g[11], 12)} : {mp.nstr(g[33]/g[11], 12)}")

# ============================================================================
print("\n【§二】/90 之 ℚ(√5) 三元組：等比（對照）")
t = [9, 15, 27]
h = {n: gam(90, n) for n in t}
print(f"  γ9  = {mp.nstr(h[9], 18)}  ((3−√5)/2)")
print(f"  γ15 = {mp.nstr(h[15], 18)}  (1)")
print(f"  γ27 = {mp.nstr(h[27], 18)}  ((3+√5)/2)")
gpv = h[15] ** 2 - h[9] * h[27]
apv = (h[15] - h[9]) - (h[27] - h[15])
print(f"\n  GP 檢定：γ15² − γ9·γ27 = {mp.nstr(gpv, 3)} ⟹ **等比**")
print(f"           比值 r = {mp.nstr(h[15]/h[9], 16)}；φ² = {mp.nstr(((1+mp.sqrt(5))/2)**2, 16)}；"
      f"|偏差| = {mp.nstr(abs(h[15]/h[9] - ((1+mp.sqrt(5))/2)**2), 3)}")
print(f"  AP 檢定：(γ15−γ9) − (γ27−γ15) = {mp.nstr(apv, 6)} ⟹ **非等差**")

# ============================================================================
print("\n【§三】★ 全鏈掃描：兩鏈有無**任何**三模等比（T2）")
print(L)
for x, tag in ((88, "/88"), (90, "/90")):
    gg = [mp.mpf(0)] + [gam(x, n) for n in range(1, N + 1)]
    gps, aps = [], []
    for a, b, c in itertools.combinations(range(1, N + 1), 3):
        if abs(gg[b] ** 2 - gg[a] * gg[c]) < TOL:
            gps.append((a, b, c))
        if abs((gg[b] - gg[a]) - (gg[c] - gg[b])) < TOL:
            aps.append((a, b, c))
    print(f"  {tag}：等比三元組 **{len(gps)}** 個；等差三元組 **{len(aps)}** 個")
    if gps:
        print(f"        等比：{gps[:8]}{' …' if len(gps) > 8 else ''}")
        # ★ 2026-11-02 審計補（⑦ 反向覆蓋）：列出每個 GP 三元組之比值，令 docs/29 之三位數有 data 落地
        for (a, b, c) in gps[:8]:
            _r1 = gg[b] / gg[a]      # 用局部 γ 表（gg 以索引 1..N）
            _r2 = gg[c] / gg[b]
            print(f"          比值 {a},{b},{c}：r = {mp.nstr(_r1, 12)}（r1 = r2：{abs(_r1 - _r2) < 1e-30}）")
    if aps:
        print(f"        等差：{aps[:8]}{' …' if len(aps) > 8 else ''}")

# ============================================================================
print("\n【§四】結構根源：補償對稱為何強制 AP")
print(L)
print(f"""  對任何子鏈 /M，γ_n + γ_(M−n) = 4 ⟹ 取 n, M/2, M−n（M 偶）：
     γ_n + γ_(M−n) = 4 = 2·γ_(M/2)   （γ_(M/2) = 2）
  ⟹ 三項**恆**成 AP，公差 = γ_(M/2) − γ_n，中心 = 2
  /8：公差 = 2 − (2−√2) = **√2**
  ⟹ AP 係補償對稱之**恆等後果**，非可選結構 ⟹ 唔可能承載「三代質量級數」（AP 非尺度不變）
  /90 之 GP 則屬**偶然**（不來自 γ_n+γ_(45−n) = 4 之恆等，須逐例驗證）""")

# ============================================================================
print("\n【§五】判定（X1）")
print(L)
print(f"""  ✅ X1 得答：/88 之 ℚ(√2) 扇區**有**階梯，但係**等差**（公差 √2，中心 2）：
     γ11 : γ22 : γ33 = 1 : {mp.nstr(g[22]/g[11], 6)} : {mp.nstr(g[33]/g[11], 6)}（= 1 : 2+√2 : 3+2√2）
     而 /90 之三元組係**等比**（比 φ² = 2.618），γ9 : γ15 : γ27 = 1 : φ² : φ⁴。
  ✅ 全鏈掃描：/88 之等比三元組 = 見 §三（若 0 ⟹ **冇任何乘性階梯**）；
     等差三元組 = 見 §三（AP 由補償對稱強制，數目大）。
  ⟹ 結構對比：/88 **只有加性結構**（能量守恆／AP）；/90 方有**乘性結構**（GP／φ-冪）。
     此與 docs/28 之域論結論同源：√5 缺席 ⟹ φ 缺席 ⟹ 無乘性階梯。
  🔴 未做：AP 1 : 2+√2 : 3+2√2 之質量解讀 —— 與 φ-階梯同屬禁區（幂律質量擬合），不推。
""")
print(L)
raise SystemExit(0)