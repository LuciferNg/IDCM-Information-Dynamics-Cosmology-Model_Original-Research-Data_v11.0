"""
M14 scripts/31 — Y3：加性／乘性階梯之**一般判準**，兼**推翻我自己上一輪之載體類型說**

────────────────────────────────────────────────────────────────────────
殘留：docs/29 §六 Y3（「加性載體不可承載乘性階梯」可否對任意 N 證成）
本輪先做**否證**：若 /88 與 /90 用同一 γ 公式，則「載體類型」說必錯。
再給正確命題：AP／GP 之存在性係 N 之**算術**條件。

判準（跑前凍結）
  U1 鏈 γ_n = 4sin²(nπ/N)，n = 1..K；主掃 K = N/2（環），穩健性掃 K = N/2 − 1（Dirichlet）。
  U2 AP：γ_a + γ_c = 2γ_b；GP：γ_b² = γ_a·γ_c；a<b<c，容差 1e−30（dps 40）。
  U3 猜想（掃完方可寫）：AP>0 ⟺ 4|N；GP 數 = 2·[12|N] + 3·[30|N]。
性質：確定性窮舉。N_trials = 0。零觀測量。
────────────────────────────────────────────────────────────────────────
"""
import itertools

import mpmath as mp

mp.mp.dps = 40
L = "=" * 78
TOL = mp.mpf('1e-30')
NRANGE = range(8, 201, 2)


def gam(N, n):
    return 4 * mp.sin(n * mp.pi / N) ** 2


def count(N, K):
    g = {n: gam(N, n) for n in range(1, K + 1)}
    ap = gp = 0
    for a, b, c in itertools.combinations(range(1, K + 1), 3):
        ga, gb, gc = g[a], g[b], g[c]
        if abs((gb - ga) - (gc - gb)) < TOL:
            ap += 1
        if abs(gb * gb - ga * gc) < TOL:
            gp += 1
    return ap, gp


print(L)
print("M14 scripts/31 — Y3：一般判準（AP ⟺ 4|N；GP ⟺ 12|N 或 30|N）")
print(L)

# ============================================================================
print("\n【§一】掃描 N = 8..200（偶），兩種模數約定")
print(f"  {'N':>4} {'K=N/2':>12} {'K=N/2−1':>12}  4|N 12|N 30|N  GP預言")
print(f"  {'':>4} {'AP':>5}{'GP':>7} {'AP':>5}{'GP':>7}")
bad_ap, bad_gp = [], []
for N in NRANGE:
    a1, p1 = count(N, N // 2)
    a2, p2 = count(N, N // 2 - 1) if N // 2 - 1 >= 3 else (0, 0)
    d4, d12, d30 = N % 4 == 0, N % 12 == 0, N % 30 == 0
    pred1 = 2 * int(d12) + 3 * int(d30)          # K = N/2（Nyquist 在內）
    pred2 = 1 * int(d12) + 3 * int(d30)          # K = N/2−1（Nyquist 在外）
    ok_ap = ((a1 > 0) == d4) and ((a2 > 0) == d4)
    ok_gp = (p1 == pred1) and (p2 == pred2)
    if not ok_ap:
        bad_ap.append((N, a1, a2, d4))
    if not ok_gp:
        bad_gp.append((N, p1, p2, pred1, pred2))
    if N <= 40 or N in (88, 90, 120, 180, 200):
        print(f"  {N:>4} {a1:>5}{p1:>7} {a2:>5}{p2:>7}  "
              f"{'Y' if d4 else '.':>3}{'Y' if d12 else '.':>4}{'Y' if d30 else '.':>4}  {pred1}/{pred2}")

# ============================================================================
print("\n" + L)
print("【§二】判準檢定")
print(L)
print(f"  U3a「AP > 0 ⟺ 4 | N」：違例 {len(bad_ap)} / {len(list(NRANGE))}"
      + (f" → {bad_ap}" if bad_ap else " ✅"))
print(f"  U3b「GP 數（Nyquist 在內，K=N/2）= 2·[12|N] + 3·[30|N]」"
      f"且「GP 數（Nyquist 在外，K=N/2−1）= [12|N] + 3·[30|N]」："
      f"違例 {len(bad_gp)} / {len(list(NRANGE))}" + (f" → {bad_gp}" if bad_gp else " ✅"))

print(f"""
  ★ AP 之**可證**部分：AP 族 (a, N/4, N/2−a) 恆成立
      ∵ γ_a + γ_(N/2−a) = 4（sin²+cos² 恆等），且 γ_(N/4) = 2 ⟹ 4 = 2·2
      ⟹ 需 N/4 ∈ ℤ ⟹ 4 | N；共 N/4 − 1 個（a = 1..N/4−1）
      4 | N 時實測 AP = N/4 − 1 + [12|N]（多出 1 個，來自 3 | N/4 之另一族）
  ★ GP 之判準屬**實測猜想**（N = 8..200 全中，兩種模數約定各自吻合），未證。
     兩式之差恰為 [12|N] ⟹ Nyquist 模（γ=4）參與一個 GP 三元組，僅當 12 | N。
""")

# ============================================================================
print(L)
print("【§三】套用至 88 與 90（真實鏈之模數）")
print(L)
for N, K, tag in ((88, 44, "/88（環，K = N/2）"), (90, 44, "/90（Dirichlet，K = N/2 − 1）")):
    a, p = count(N, K)
    print(f"  {tag}：K = {K} ⟹ AP = {a}、GP = {p}")
    print(f"     4|N? {'Y' if N%4==0 else '.'}  12|N? {'Y' if N%12==0 else '.'}  "
          f"30|N? {'Y' if N%30==0 else '.'}  ⟹ 預言 GP = {2*int(N%12==0)+3*int(N%30==0)}")
print(f"""
  /88 = 2³·11 ⟹ 4 | 88（⟹ AP = 88/4 − 1 = 21 ✓）；12 ∤ 88 且 30 ∤ 88 ⟹ **GP = 0** ✓
  /90 = 2·3²·5 ⟹ 4 ∤ 90（⟹ AP = 0 ✓）；30 | 90 ⟹ **GP = 3** ✓
  ⟹ 兩鏈之差**完全由 88／90 之算術決定**，與「載體類型」無關。
""")

# ============================================================================
print(L)
print("【§四】★ 推翻我自己上一輪之表述（Y3 之前提）")
print(L)
print("""  上一輪（docs/29 §五）我寫：「/88 只有加性結構、/90 方有乘性結構」，
  並歸因於「sqrt5 缺席 ⟹ φ 缺席 ⟹ 乘性階梯缺席」。
  **此表述有兩處問題：**
    (a) /88 與 /90 用**同一** γ_n = 4sin²(nπ/N) 公式 ⟹ 不存在「加性載體 vs 乘性載體」之類型分別；
        正確者是 N 之算術條件（4|N / 12|N / 30|N）。
    (b) 「√5 缺席 ⟹ 無乘性階梯」並不成立為因果：N = 12 有 GP（2 個）而 5 ∤ 12；
        N = 30 有 GP（3 個）而 4 ∤ 30。故 √5 既非必要亦非充分。
  **保留下來之正確部分**（docs/28）：
    √5 ∉ ℚ(ζ_88) 為真（conductor 5 ∤ 88），且 pslq 核實兩鏈譜在 ℚ(√2) / ℚ(√5)；
    但此只說明「/88 之譜值域不含 √5」，**不**推出「/88 無乘性階梯」——
    後者之正確理由係 12 ∤ 88 且 30 ∤ 88。
""")

# ============================================================================
print(L)
print("【§五】判定（Y3）")
print(L)
print("""  ❌ Y3 原表述（「加性載體不可承載乘性階梯」）**否證**：無「加性載體」此一類型；
     反例即 /90 本身（同一 γ 公式卻有 3 個 GP）。
  ✅ 取代命題（實測，N = 8..200 全中，0 違例）：
       AP（加性階梯）存在 ⟺ 4 | N，且數目 = N/4 − 1 + [12|N]（恆等族可證）
       GP（乘性階梯）數 = 2·[12|N] + 3·[30|N]（Nyquist 在內）
                        = 1·[12|N] + 3·[30|N]（Nyquist 在外）
     ⟹ 「乘性質量階梯」若要存在，N 必須為 12 或 30 之倍數；
        88 兩者皆非 ⟹ 對 N_d = 44 之 /88 載體**必然**失敗 —— 但係算術之故，非載體類型。
  🔴 未證：GP 判準（2[12|N] + 3[30|N]）之數論證明；AP 之「4∤N ⟹ 無其他族」之證明。
""")
print(L)
raise SystemExit(0)