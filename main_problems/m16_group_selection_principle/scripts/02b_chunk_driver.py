#!/usr/bin/python3
# -*- coding: utf-8 -*-
"""
scripts/02b_chunk_driver.py — 將「階 ≤ 500 全部群」之掃描切成平衡分片（含單一階內之子區間切分），
為每片產生一支 GAP 腳本（路徑寫死：本機 GAP 未綁 ARGV），供 scripts/run_02_parallel.sh 並行執行。

不改變掃描內容：所有 (n, i0..i1) 任務之聯集 = [1..500] 之全部 SmallGroups。
成本權重 w(n) 只作負載平衡（不影響數學）。
"""
import os, sys, json, math

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DATA = os.path.join(ROOT, "data")
CH = os.path.join(DATA, "chunks")
NCHUNK = int(sys.argv[1]) if len(sys.argv) > 1 else 11
TASK = int(sys.argv[2]) if len(sys.argv) > 2 else 4000

counts = []
with open(os.path.join(DATA, "order_counts.txt")) as f:
    for line in f:
        p = line.split()
        if len(p) == 2 and p[0].isdigit():
            counts.append((int(p[0]), int(p[1])))
total = sum(c for _, c in counts)


def weight(n):
    if n % 64 == 0:
        return 8.0
    if n % 32 == 0:
        return 3.0
    if n % 16 == 0:
        return 2.0
    return 1.0


tasks = []   # (n, i0, i1, w)
for n, c in counts:
    k = math.ceil(c / TASK)
    step = math.ceil(c / k)
    i = 1
    while i <= c:
        j = min(c, i + step - 1)
        tasks.append((n, i, j, (j - i + 1) * weight(n)))
        i = j + 1
print(f"orders={len(counts)} groups={total} tasks={len(tasks)} chunks={NCHUNK}")

os.makedirs(CH, exist_ok=True)
bins = [[] for _ in range(NCHUNK)]
load = [0.0] * NCHUNK
for t in sorted(tasks, key=lambda x: -x[3]):
    j = load.index(min(load))
    bins[j].append(t)
    load[j] += t[3]

for j in range(NCHUNK):
    assert bins[j], f"chunk {j} empty"
    out = os.path.join(DATA, f"chunk_{j:02d}.txt")
    script = os.path.join(CH, f"scan_{j:02d}.g")
    tl = ", ".join(f"[{n},{a},{b}]" for n, a, b, _ in sorted(bins[j]))
    body = f"""# auto-generated by scripts/02b_chunk_driver.py — chunk {j:02d}
outfile := "{out}";
tasks := [{tl}];
tot := 0;
str := OutputTextFile(outfile, false);
SetPrintFormattingStatus(str, false);
t0 := Runtime();
for t in tasks do
  for i in [t[2]..t[3]] do
    g := SmallGroup(t[1],i);
    PrintTo(str, t[1], " ", i, " ", CharacterDegrees(g), "\\n");
    tot := tot + 1;
  od;
  Print("chunk{j:02d} n=", t[1], " i=", t[2], "..", t[3], " cum=", tot, " ms=", Runtime()-t0, "\\n");
od;
CloseStream(str);
Print("CHUNK{j:02d} TOTAL ", tot, " ms=", Runtime()-t0, "\\n");
QUIT;
"""
    with open(script, "w") as f:
        f.write(body)
    print(f"chunk {j:02d}: tasks={len(bins[j])} weight={load[j]:.0f}")
with open(os.path.join(CH, "plan.json"), "w") as f:
    json.dump({"NCHUNK": NCHUNK, "total": total, "TASK": TASK,
               "bins": {f"{j:02d}": sorted(bins[j]) for j in range(NCHUNK)}}, f, indent=1)